EP.t = function (key, vars) {
  var s = (EP.strings[EP.lang] && EP.strings[EP.lang][key]) || EP.strings.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(vars[k]); });
  }
  return s;
};

// Pick the current language from a {en, ml} object.
EP.tx = function (obj) {
  if (!obj) return '';
  return obj[EP.lang] || obj.en || '';
};

EP.esc = function (s) {
  return String(s === null || s === undefined ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
};

